#!/usr/bin/env python3
"""patch_makefile.py — Generic TITAN Makefile patcher for the V2G TTCN-3 pipeline.

Purpose
-------
Patch the Makefile generated by ``makefilegen`` so that the resulting
``TestExecutable`` correctly links ``libexi_bridge.a`` (the OpenV2G dynamic
encoder bridge) and compiles with the OpenV2G include path.

This script is **generic** — it accepts all paths via CLI / environment
variables and does NOT hard-code any project-specific location. It lives in
``shared_infrastructure/build_helpers/`` so any TC project at any depth can
invoke it with an absolute path.

Required patches
----------------
1. Inject ``-I<OPENV2G_INC>`` into ``CXXFLAGS`` (header resolution).
2. Remove ``-D_GLIBCXX_USE_CXX11_ABI=0`` (incompatible with libfmt).
3. Override the ``$(EXECUTABLE): $(OBJECTS)`` link rule with a clean POSIX
   rule that:
   - Places ``libexi_bridge.a`` AFTER object files (static lib link order).
   - Links ``-lttcn3-dynamic -lcrypto -lxml2 -lpthread -ldl``.
   - Avoids TITAN's ``if g++ ... && ...; then ... fi`` /bin/sh parsing bug.

Usage
-----
::

    python3 patch_makefile.py \\
        --makefile /path/to/build/generated_cpp/Makefile \\
        --openv2g-inc /abs/path/to/shared_infrastructure/exi_engine \\
        --exi-bridge-a /abs/path/to/build_exi_bridge/libexi_bridge.a

Or via environment variables (for shell composition)::

    PATCH_MF=/path/to/Makefile
    PATCH_OPENV2G_INC=/abs/path/to/exi_engine
    PATCH_EXI_BRIDGE_A=/abs/path/to/libexi_bridge.a
    python3 patch_makefile.py

Exit codes
----------
- 0: success
- 1: usage / argument error
- 2: required file or directory missing
- 3: Makefile pattern mismatch (unexpected TITAN Makefile format)
"""

import argparse
import os
import sys


def _read_env_or_arg(arg_value, env_var, required_desc):
    """Prefer CLI value, fall back to environment variable, error if neither."""
    if arg_value:
        return arg_value
    env_value = os.environ.get(env_var)
    if env_value:
        return env_value
    print(f"[PATCH] ERROR: {required_desc} not provided "
          f"(use --{env_var.lower().replace('patch_', '').replace('_', '-')} "
          f"or env var {env_var})", file=sys.stderr)
    sys.exit(1)


def _patch_cxxflags(content, openv2g_inc):
    """Inject ``-I<openv2g_inc>`` into CXXFLAGS line.

    Robust against two Makefile shapes:
    - TITAN raw       : ``CXXFLAGS = -Wall  \\n``
    - Post-fmt-sed    : ``CXXFLAGS = -I<fmt> -I. -Wall  \\n``
    We find the first ``CXXFLAGS`` line and append ``-I<openv2g_inc>`` to
    the value if it is not already present.
    """
    import re
    needle = 'CXXFLAGS'
    if needle not in content:
        print('[PATCH] WARNING: No CXXFLAGS line found at all', file=sys.stderr)
        return content

    # Split into lines, find the FIRST CXXFLAGS line, append include.
    lines = content.split('\n')
    patched = False
    for i, line in enumerate(lines):
        stripped = line.lstrip()
        if stripped.startswith(needle) and '=' in stripped:
            # Idempotency: don't add the same include twice
            if '-I' + openv2g_inc in line:
                print('[PATCH] CXXFLAGS already contains OpenV2G include; skipping')
                return content
            lines[i] = line.rstrip('\r') + ' -I' + openv2g_inc
            patched = True
            break

    if not patched:
        print('[PATCH] WARNING: Could not find a mutable CXXFLAGS line')
        return content

    new_content = '\n'.join(lines)
    print(f'[PATCH] Injected OpenV2G include into CXXFLAGS: {openv2g_inc}')
    return new_content


def _strip_glibcxx_abi0(content):
    """Remove -D_GLIBCXX_USE_CXX11_ABI=0 (breaks fmt)."""
    if '-D_GLIBCXX_USE_CXX11_ABI=0' in content:
        content = content.replace('-D_GLIBCXX_USE_CXX11_ABI=0', '')
        print('[PATCH] Removed -D_GLIBCXX_USE_CXX11_ABI=0 (fmt-compatible)')
    return content


def _rewrite_link_rule(content, exi_bridge_a):
    """Replace the $(EXECUTABLE) link rule with a clean POSIX rule.

    Robust against two Makefile shapes:
    - TITAN default : ``$(EXECUTABLE): $(OBJECTS)\\n    if $(CXX) ... then : ; else ...\\n    fi\\n``
    - Already-patched: the whole block has been replaced by a single-line
      ``$(CXX) -o $@ ...`` recipe.
    Idempotency check: if libexi_bridge.a is already on a recipe line right
    after the EXECUTABLE target, skip the rewrite.
    """
    nl = '\n'
    tab = '\t'
    libs = ('-L/usr/lib/titan -lttcn3-dynamic -L/lib -lcrypto '
            '-L/usr/lib -lxml2 -lpthread -ldl')

    # Idempotency: if the rule already references libexi_bridge.a, leave it.
    if exi_bridge_a in content:
        print('[PATCH] Link rule already references libexi_bridge.a; skipping')
        return content

    start = content.find('$(EXECUTABLE): $(OBJECTS)' + nl)
    if start < 0:
        # Some Makefiles split EXECUTABLE declaration; try a more lenient match
        start = content.find('$(EXECUTABLE):')
        if start < 0:
            print('[PATCH] ERROR: Could not find "$(EXECUTABLE):" target',
                  file=sys.stderr)
            sys.exit(3)

    lib_pos = content.find('$(LIBRARY):', start)
    if lib_pos < 0:
        print('[PATCH] ERROR: Could not find "$(LIBRARY):" target', file=sys.stderr)
        sys.exit(3)

    blank_before = content.rfind(nl, start, lib_pos)
    end = blank_before + 1  # include the trailing \n

    original_block = content[start:end]

    new_rule = (
        '$(EXECUTABLE): $(OBJECTS)' + nl +
        tab + '$(CXX) -o $@ $(OBJECTS) ' + exi_bridge_a + ' ' + libs +
        ' $(LDFLAGS)' + nl + nl
    )

    content = content.replace(original_block, new_rule)
    print(f'[PATCH] Link rule overridden (POSIX-compatible) with {exi_bridge_a}')
    return content


def main():
    parser = argparse.ArgumentParser(
        description='Patch TITAN-generated Makefile for OpenV2G linkage.',
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument('--makefile',
                        help='Path to the Makefile to patch '
                             '(default: $PATCH_MF or ./Makefile)')
    parser.add_argument('--openv2g-inc',
                        help='Absolute path to the OpenV2G include directory '
                             '(default: $PATCH_OPENV2G_INC)')
    parser.add_argument('--exi-bridge-a',
                        help='Absolute path to libexi_bridge.a '
                             '(default: $PATCH_EXI_BRIDGE_A)')
    args = parser.parse_args()

    makefile = args.makefile or os.environ.get('PATCH_MF') or './Makefile'
    if not os.path.isfile(makefile):
        print(f'[PATCH] ERROR: Makefile not found: {makefile}', file=sys.stderr)
        sys.exit(2)

    openv2g_inc = _read_env_or_arg(args.openv2g_inc, 'PATCH_OPENV2G_INC',
                                   'OpenV2G include directory')
    exi_bridge_a = _read_env_or_arg(args.exi_bridge_a, 'PATCH_EXI_BRIDGE_A',
                                    'libexi_bridge.a absolute path')

    if not os.path.isdir(openv2g_inc):
        print(f'[PATCH] ERROR: OpenV2G include dir does not exist: {openv2g_inc}',
              file=sys.stderr)
        sys.exit(2)
    if not os.path.isfile(exi_bridge_a):
        print(f'[PATCH] ERROR: libexi_bridge.a does not exist: {exi_bridge_a}',
              file=sys.stderr)
        sys.exit(2)

    print(f'[PATCH] Makefile     : {os.path.abspath(makefile)}')
    print(f'[PATCH] OpenV2G inc  : {openv2g_inc}')
    print(f'[PATCH] exi_bridge.a : {exi_bridge_a}')

    with open(makefile, 'r', encoding='utf-8') as f:
        content = f.read()

    content = _patch_cxxflags(content, openv2g_inc)
    content = _strip_glibcxx_abi0(content)
    content = _rewrite_link_rule(content, exi_bridge_a)

    with open(makefile, 'w', encoding='utf-8') as f:
        f.write(content)

    print('[PATCH] Makefile patched successfully.')


if __name__ == '__main__':
    main()